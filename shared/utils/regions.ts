/**
 * The controlled vocabulary behind an entry's location.
 *
 * `location` is a display string and nothing more -- "Brooklyn, NY",
 * "Toronto, ON", "Reykjavik, IS". The country an entry counts towards is the
 * `country` column, an ISO 3166-1 alpha-2 code chosen from this list. Nothing
 * reads a country back out of the display string, which is the point: the two
 * are produced together from the same picks, so there is no format to parse and
 * no way for "CA" to mean California here and Canada there.
 *
 * Lives in shared/ because both halves need it: the submission wizard and the
 * admin edit row build the selects from it, and the endpoints behind them
 * check what arrives against it.
 */

export interface Region {
  code: string;
  name: string;
}

