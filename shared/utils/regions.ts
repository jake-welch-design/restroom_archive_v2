export const COUNTRIES: readonly Region[] = [...COUNTRY_LIST].sort((a, b) =>
  a.name.localeCompare(b.name, "en"),
);

const COUNTRY_BY_CODE = new Map(COUNTRIES.map((c) => [c.code, c]));

const SUBDIVISIONS: Record<string, readonly Region[]> = {
  US: US_STATES,
  CA: CA_PROVINCES,
};

/** The subdivisions to offer for a country, or null where none are collected. */
export function subdivisionsFor(country: string): readonly Region[] | null {
  return SUBDIVISIONS[country] ?? null;
}

/** True if `country` is a code this archive files entries under. */
export function isCountryCode(country: string): boolean {
  return COUNTRY_BY_CODE.has(country);
}

/** True if `code` is a subdivision of `country`. */
export function isSubdivisionCode(country: string, code: string): boolean {
  return subdivisionsFor(country)?.some((r) => r.code === code) ?? false;
}

export function countryName(country: string): string | undefined {
  return COUNTRY_BY_CODE.get(country)?.name;
}

/**
 * The display string, built from the same picks that set `country`.
 *
 * The trailing token is the subdivision where one was collected and the country
 * otherwise, which is what the catalog has always shown: "Brooklyn, NY",
 * "Toronto, ON", "Reykjavik, IS". It is for reading, and nothing derives the
 * country from it.
 */
export function composeLocation(
  city: string,
  country: string,
  subdivision?: string | null,
): string {
  const trimmed = city.trim().replace(/\s*,\s*$/, "");
  const suffix =
    subdivisionsFor(country) && subdivision ? subdivision : country;
  return `${trimmed}, ${suffix}`;
}

/**
 * The city half of a stored location -- everything before the trailing token.
 * Only used to seed the edit form from an existing row; nothing depends on it
 * being exactly right, because the row's country is stored separately.
 */
export function cityFromLocation(location: string): string {
  const cut = location.lastIndexOf(",");
  return cut === -1 ? location.trim() : location.slice(0, cut).trim();
}

/** The trailing token of a stored location, uppercased. */
export function subdivisionFromLocation(location: string): string {
  const cut = location.lastIndexOf(",");
  return cut === -1
    ? ""
    : location
        .slice(cut + 1)
        .trim()
        .toUpperCase();
}
